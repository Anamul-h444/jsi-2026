  Object.values(SPECIAL_PAY).forEach(s => {
    if (s.all) L.push(`- ${s.label}: ${s.all.old}→${s.all.new}`);
    else L.push(`- ${s.label}: জেসিও ${s.JCO.old}→${s.JCO.new}; সার্জেন্ট ${s.SGT.old}→${s.SGT.new}; কর্পোরাল ও তদনিম্ন ${s.CPL.old}→${s.CPL.new}`);
  });
